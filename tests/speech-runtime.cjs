const path=require('node:path'),fs=require('node:fs'),assert=require('node:assert/strict'),crypto=require('node:crypto');
const {SpeechRuntime}=require('../dist/main/speech'),{audioInput,wavData}=require('./audio.cjs');
const root=path.resolve(__dirname,'..'),runtime=new SpeechRuntime(path.join(root,'speech-runtime'),()=> 'Calendar events and tasks.');
(async()=>{try{
  const started=performance.now(),[first,second]=await Promise.all([runtime.start(),runtime.start()]);
  assert.equal(first.pid,second.pid);const startupMs=Math.round(performance.now()-started);
  const final=await runtime.transcribe(audioInput('test-results/voice-command.wav'));assert.match(final.text,/exam.*Friday/i);
  const long=audioInput('test-results/voice-long.wav'),duration=wavData('test-results/voice-long.wav').seconds;
  assert.ok(duration>120);assert.ok(long.audio.byteLength>1440000);
  const longStarted=performance.now(),result=await runtime.transcribe(long);
  const longTranscriptionMs=Math.round(performance.now()-longStarted);
  assert.match(result.text,/exam.*Friday/i);assert.match(result.text,/buy notebooks/i);
  const pendingInput=audioInput('test-results/voice-long.wav'),pending=runtime.transcribe(pendingInput).then(()=>false,()=>true);
  await new Promise(resolve=>setTimeout(resolve,100));const cancelStarted=performance.now();await runtime.cancel(pendingInput.requestId);
  assert.equal(await pending,true);assert.equal((await runtime.start()).pid,first.pid);
  const cancelMs=Math.round(performance.now()-cancelStarted);
  const retry=await runtime.transcribe(audioInput('test-results/voice-command.wav'));assert.match(retry.text,/exam.*Friday/i);
  await assert.rejects(runtime.transcribe({audio:new Uint8Array([1,2,3]).buffer,mimeType:'audio/wav',requestId:crypto.randomUUID()}),/Local speech failed/);
  assert.equal((await runtime.start()).pid,first.pid);
  assert.equal((await fetch(`http://127.0.0.1:${first.port}/health`)).status,403);
  const report={passed:true,startupMs,durationSeconds:duration,longTranscriptionMs,cancelMs,final:result.text,workerReused:true};
  fs.writeFileSync('test-results/speech-runtime-report.json',JSON.stringify(report,null,2));console.log(JSON.stringify(report));
}finally{runtime.stop();}})().catch(error=>{console.error(error);console.log(runtime.status);process.exitCode=1;});
