import { contextBridge, ipcRenderer } from 'electron';
import { PlannerAPI } from '../shared/model';
const api: PlannerAPI = {
  snapshot: () => ipcRenderer.invoke('planner:snapshot'),
  mutate: input => ipcRenderer.invoke('planner:mutate', input),
  undo: revision => ipcRenderer.invoke('planner:undo',revision),
  organizePreview:()=>ipcRenderer.invoke('planner:organize-preview'),
  preferences: input => ipcRenderer.invoke('planner:preferences', input),
  getDraft:()=>ipcRenderer.invoke('assistant:get-draft'),
  applyDraft:input=>ipcRenderer.invoke('assistant:apply-draft',input),
  editDraft:input=>ipcRenderer.invoke('assistant:edit-draft',input),
  dismissDraft:input=>ipcRenderer.invoke('assistant:dismiss-draft',input),
  onDraftChanged:fn=>{const listener=(_event:unknown,event:any)=>{if(event.type==='draftchange')fn(event.draft);};ipcRenderer.on('assistant:event',listener);return()=>ipcRenderer.removeListener('assistant:event',listener);},
  chat: input => ipcRenderer.invoke('assistant:chat', input),
  checkChatInput: input => ipcRenderer.invoke('assistant:check-input', input),
  cancelChat: () => ipcRenderer.invoke('assistant:cancel'),
  newChat:()=>ipcRenderer.invoke('assistant:reset'),
  onChatEvent:fn=>{const listener=(_event:unknown,event:any)=>fn(event);ipcRenderer.on('assistant:event',listener);return()=>ipcRenderer.removeListener('assistant:event',listener);},
  status: () => ipcRenderer.invoke('assistant:status'),
  runtimeSettings:()=>ipcRenderer.invoke('assistant:settings'),
  configureRuntime:input=>ipcRenderer.invoke('assistant:configure',input),
  retryRuntime: () => ipcRenderer.invoke('assistant:retry'),
  startSpeech: () => ipcRenderer.invoke('speech:start'),
  transcribe: input => ipcRenderer.invoke('speech:transcribe',input),
  speak: input=>ipcRenderer.invoke('speech:speak',input),
  cancelSpeech: requestId => ipcRenderer.invoke('speech:cancel',requestId),
  speechStatus: () => ipcRenderer.invoke('speech:status'),
  createDictation:input=>ipcRenderer.invoke('dictation:create',input),
  appendDictation:input=>ipcRenderer.invoke('dictation:append',input),
  checkpointDictation:input=>ipcRenderer.invoke('dictation:checkpoint',input),
  listDictations:()=>ipcRenderer.invoke('dictation:list'),
  getDictation:id=>ipcRenderer.invoke('dictation:get',id),
  restoreDictation:input=>ipcRenderer.invoke('dictation:restore',input),
  discardDictation:id=>ipcRenderer.invoke('dictation:discard',id),
  previewSpeech:input=>ipcRenderer.invoke('speech:preview',input),
  transcribeDictation:input=>ipcRenderer.invoke('dictation:transcribe',input),
  onSpeechProgress:fn=>{const listener=(_event:unknown,event:any)=>fn(event);ipcRenderer.on('speech:progress',listener);return()=>ipcRenderer.removeListener('speech:progress',listener);},
  onPrepareClose:fn=>{const listener=()=>{void fn().finally(()=>ipcRenderer.invoke('app:close-ready')).catch(()=>{});};ipcRenderer.on('app:prepare-close',listener);return()=>ipcRenderer.removeListener('app:prepare-close',listener);},
  onChanged: fn => { const listener = () => fn(); ipcRenderer.on('planner:changed', listener); return () => ipcRenderer.removeListener('planner:changed', listener); },
  onStatus: fn => { const listener = (_event: unknown, status: any) => fn(status); ipcRenderer.on('assistant:status', listener); return () => ipcRenderer.removeListener('assistant:status', listener); }
};
contextBridge.exposeInMainWorld('planner', api);
